import argparse
import json
from pathlib import Path

from common import build_model, get_device, load_dataset, save_json, set_seed


def parse_args():
    parser = argparse.ArgumentParser(description='Evaluate a saved MIMIC-IV-MM PPO checkpoint on the test split.')
    parser.add_argument('--checkpoint', required=True, help='best_model.pth generated by train.py')
    parser.add_argument('--large_data_path', default=None, help='Override the large-model data directory')
    parser.add_argument('--small_data_path', default=None, help='Override the small-model data directory')
    parser.add_argument('--output', default='./outputs/test_metrics.json')
    parser.add_argument('--batch_size', type=int, default=64)
    parser.add_argument('--device', default='auto')
    parser.add_argument('--threshold_mode', choices=['ratio', 'argmax'], default='ratio',
                        help='ratio follows the original validation-based positive-ratio rule')
    args = parser.parse_args()
    if args.batch_size < 1:
        parser.error('batch_size must be positive')
    return args


def predict(model, loader, device):
    import numpy as np
    import torch
    labels, probabilities, weights = [], [], []
    model.eval()
    with torch.no_grad():
        for image, text, time, small, target in loader:
            image, text, time, small = [x.to(device, dtype=torch.float32) for x in (image, text, time, small)]
            logits, _, policy = model(image, text, time, small, training=False)
            if not torch.isfinite(logits).all():
                raise FloatingPointError('Non-finite logits during evaluation.')
            labels.append(torch.as_tensor(target).cpu().numpy().reshape(-1))
            probabilities.append(torch.softmax(logits, dim=1).cpu().numpy())
            weights.append(policy['expert_probs'].cpu().numpy())
    if not labels:
        raise ValueError('Cannot evaluate an empty data split.')
    return np.concatenate(labels), np.concatenate(probabilities), np.concatenate(weights)


def main(args):
    import numpy as np
    import torch
    from torch.utils.data import DataLoader
    from sklearn.metrics import (roc_auc_score, average_precision_score,
                                 precision_recall_curve, auc, classification_report)
    device = get_device(args.device)
    checkpoint = torch.load(args.checkpoint, map_location='cpu', weights_only=True)
    config = checkpoint['config'].copy()
    if args.large_data_path is not None:
        config['large_data_path'] = args.large_data_path
    if args.small_data_path is not None:
        config['small_data_path'] = args.small_data_path
    set_seed(config['seed'])
    # The full trained state includes the classifier; the small-model checkpoint
    # and training data are not needed to initialize evaluation.
    model = build_model(config, device)
    model.load_state_dict(checkpoint['model_state_dict'], strict=True)
    model.set_gate_temperature(config['gate_temperature'])
    threshold = None
    if args.threshold_mode == 'ratio':
        validation = DataLoader(load_dataset('val', config), batch_size=args.batch_size, shuffle=False)
        _, val_probs, _ = predict(model, validation, device)
        ratio = float(checkpoint['positive_ratio'])
        negative_count = int(len(val_probs) * (1 - ratio))
        if not 0 < negative_count < len(val_probs):
            raise ValueError('Validation set/positive ratio cannot define an interior threshold; use --threshold_mode argmax.')
        partition = np.partition(val_probs[:, 1], negative_count)
        threshold = float((partition[:negative_count].max() + partition[negative_count]) / 2)
    testing = DataLoader(load_dataset('test', config), batch_size=args.batch_size, shuffle=False)
    labels, probabilities, weights = predict(model, testing, device)
    if set(np.unique(labels)) != {0, 1}:
        raise ValueError('Binary AUROC requires both classes in the test split.')
    predicted = probabilities.argmax(axis=1) if threshold is None else (probabilities[:, 1] >= threshold).astype(int)
    precision, recall, _ = precision_recall_curve(labels, probabilities[:, 1])
    expert_names = ['image', 'text', 'time', 'image_text', 'image_time', 'text_time', 'image_text_time']
    result = {'task': config['task'], 'checkpoint': str(args.checkpoint),
              'epoch': checkpoint['epoch'], 'best_val_auroc': checkpoint['best_val_auroc'],
              'threshold_mode': args.threshold_mode, 'threshold': threshold,
              'auroc': float(roc_auc_score(labels, probabilities[:, 1])),
              'ap': float(average_precision_score(labels, probabilities[:, 1])),
              'auprc': float(auc(recall, precision)),
              'report': classification_report(labels, predicted, labels=[0, 1],
                         target_names=['negative', 'positive'], output_dict=True, zero_division=0),
              'expert_weights': dict(zip(expert_names, map(float, weights.mean(axis=0))))}
    save_json(args.output, result)
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main(parse_args())
